"""Filesystem payload library: one folder per bundle under PAYLOAD_LIBRARY_DIR.

A bundle folder holds the payload/lure files plus a notes markdown and a
favicon .ico - both auto-generated by the panel when missing. Everything read
back is rendered as escaped text (never executed) or served as bytes.
"""
import re
import secrets
from pathlib import Path

from django.conf import settings

TEXT_EXTS = {".html", ".htm", ".css", ".js", ".mjs", ".md", ".txt", ".json",
             ".svg", ".xml", ".csv"}

_NAME_RE = re.compile(r"^[A-Za-z0-9][A-Za-z0-9._-]{0,80}$")


def library_dir() -> Path:
    return Path(getattr(settings, "PAYLOAD_LIBRARY_DIR", settings.BASE_DIR / "payloads"))


def slugify_name(name):
    """Folder-safe bundle name from a file or label."""
    base = re.sub(r"[^A-Za-z0-9._-]+", "-", (name or "bundle").strip()).strip(".-_").lower()
    return (base or "bundle")[:80]


def bundle_path(name) -> Path:
    """Resolve and confine a bundle name to the library directory."""
    if not _NAME_RE.fullmatch(name or ""):
        raise ValueError("invalid bundle name")
    root = library_dir().resolve()
    path = (root / name).resolve()
    if path.parent != root:
        raise ValueError("invalid bundle name")
    return path


def _file_info(path, root=None):
    name = str(path.relative_to(root)) if root is not None else path.name
    return {"name": name, "size": path.stat().st_size, "ext": path.suffix.lower()}


def list_bundles():
    """All bundle folders with their notes/icon presence flags."""
    root = library_dir()
    if not root.is_dir():
        return []
    bundles = []
    for folder in sorted(p for p in root.iterdir() if p.is_dir()):
        files = [f for f in sorted(folder.rglob("*")) if f.is_file()]
        bundles.append({
            "name": folder.name,
            "files": [_file_info(f, folder) for f in files],
            "has_notes": notes_file(folder) is not None,
            "has_icon": icon_file(folder) is not None,
        })
    return bundles


def notes_file(folder: Path):
    for md in sorted(folder.glob("*.md")):
        return md
    return None


def icon_file(folder: Path):
    if (folder / "favicon.ico").is_file():
        return folder / "favicon.ico"
    for ico in sorted(folder.glob("*.ico")):
        return ico
    return None


def ensure_notes(folder: Path, name=None):
    """Create a README.md scaffold when the bundle has no markdown notes."""
    if notes_file(folder) is not None:
        return
    from django.utils import timezone
    files = "\n".join(f"- {f.relative_to(folder)}" for f in sorted(folder.rglob("*")) if f.is_file()) or "- (empty)"
    (folder / "README.md").write_text(
        f"# {name or folder.name}\n\n"
        f"Bundle created {timezone.now():%Y-%m-%d %H:%M} UTC.\n\n"
        f"## Files\n\n{files}\n\n"
        f"## Operator notes\n\n(none yet)\n",
        encoding="utf-8")


def ensure_icon(folder: Path):
    """Generate a random favicon.ico when the bundle has none."""
    if icon_file(folder) is not None:
        return
    (folder / "favicon.ico").write_bytes(generate_ico())


# ─── Minimal ICO writer (no imaging deps) ────────────────────────────────────

def _rgb(value):
    value = value.lstrip("#")
    return int(value[0:2], 16), int(value[2:4], 16), int(value[4:6], 16)


def generate_ico():
    """A random 16x16 .ico that looks designed: mirrored symmetry, a dark
    ground, a saturated accent, and a corner ring. Valid everywhere."""
    palettes = [
        ("#0d1117", "#3fb68b", "#7ee787"), ("#10131a", "#58a6ff", "#79c0ff"),
        ("#161b22", "#d29922", "#eac54f"), ("#14101a", "#f778ba", "#ff9ecf"),
        ("#0e1512", "#7ee787", "#3fb68b"), ("#18120e", "#ff9e64", "#ffc777"),
        ("#12141c", "#89b4fa", "#b4befe"), ("#161211", "#f38ba8", "#eba0ac"),
    ]
    background, primary, secondary = map(_rgb, secrets.choice(palettes))
    pattern = secrets.randbelow(4)

    def on(x, y):
        if pattern == 0:  # mirrored wedges
            qx, qy = (x if x < 8 else 15 - x), (y if y < 8 else 15 - y)
            return qx >= qy
        if pattern == 1:  # quadrant checker
            return ((x // 4) + (y // 4)) % 2 == 0
        if pattern == 2:  # centered diamond
            return abs(x - 7.5) + abs(y - 7.5) <= 7
        # concentric rings
        dist = ((x - 7.5) ** 2 + (y - 7.5) ** 2) ** 0.5
        return int(dist) % 3 == 0

    rows = []
    for y in range(16):
        for x in range(16):
            ring = x in (0, 15) or y in (0, 15)
            if ring:
                color = secondary
            elif on(x, y):
                color = primary
            else:
                color = background
            r, g, b = color
            rows.append(bytes((b, g, r, 255)))  # BGRA
    pixels = b"".join(reversed(rows))  # bottom-up
    and_mask = b"\x00" * (16 * 4)  # 1bpp, 4-byte-padded rows, fully opaque
    image = pixels + and_mask
    header = (
        (40).to_bytes(4, "little") + (16).to_bytes(4, "little", signed=True)
        + (32).to_bytes(4, "little", signed=True)  # height counts XOR+AND
        + (1).to_bytes(2, "little") + (32).to_bytes(2, "little")
        + (0).to_bytes(4, "little") + len(image).to_bytes(4, "little")
        + (0).to_bytes(4, "little") * 4
    )
    entry = (bytes((16, 16, 0, 0)) + (1).to_bytes(2, "little") + (32).to_bytes(2, "little")
             + (len(header) + len(image)).to_bytes(4, "little") + (22).to_bytes(4, "little"))
    return b"\x00\x00\x01\x00\x01\x00" + entry + header + image


# ─── Bundle lifecycle ────────────────────────────────────────────────────────

def create_bundle(name, uploaded=None, notes=""):
    """Create a bundle folder with notes + icon; optionally store an upload."""
    root = library_dir()
    root.mkdir(parents=True, exist_ok=True)
    folder = bundle_path(slugify_name(name))
    suffix = 2
    while folder.exists():
        folder = bundle_path(f"{slugify_name(name)}-{suffix}")
        suffix += 1
    folder.mkdir()
    if uploaded is not None:
        target = folder / Path(getattr(uploaded, "name", "payload.bin")).name
        with target.open("wb") as out:
            for chunk in uploaded.chunks() if hasattr(uploaded, "chunks") else [uploaded.read()]:
                out.write(chunk)
    ensure_notes(folder)
    ensure_icon(folder)
    if notes:
        md = notes_file(folder)
        md.write_text(md.read_text(encoding="utf-8").replace("(none yet)", notes[:4000]),
                      encoding="utf-8")
    return folder


def register_upload(uploaded, label=""):
    """Every uploaded payload also lands in the library as its own bundle."""
    name = slugify_name(label or getattr(uploaded, "name", "payload"))
    uploaded.seek(0) if hasattr(uploaded, "seek") else None
    return create_bundle(name, uploaded=uploaded)


def read_notes(folder: Path):
    md = notes_file(folder)
    return md.read_text(encoding="utf-8", errors="replace") if md else ""


def save_notes(folder: Path, content):
    md = notes_file(folder)
    if md is None:
        md = folder / "README.md"
    md.write_text(content[:20000], encoding="utf-8")


def import_as_lure(name, slug, user):
    """Copy a bundle's text files into a new lure site."""
    from .models import LureSite
    folder = bundle_path(name)
    if not folder.is_dir():
        raise ValueError("bundle not found")
    site = LureSite.objects.create(
        name=name.replace("-", " ").replace("_", " ").title(),
        slug=slug, description=f"Imported from payload library bundle '{name}'",
        created_by=user)
    skipped = []
    for file in sorted(folder.rglob("*")):
        if not file.is_file():
            continue
        rel = str(file.relative_to(folder))
        if file.suffix.lower() in TEXT_EXTS:
            site.files.create(path=rel,
                              content=file.read_text(encoding="utf-8", errors="replace"))
        else:
            skipped.append(rel)
    if not site.files.exists():
        site.files.create(path="index.html", content=f"<h1>{site.name}</h1>")
    return site, skipped


# ─── Template library (./data/templates/) ────────────────────────────────────

def templates_dir(kind) -> Path:
    """./data/templates/<kind>/ - confined by construction."""
    root = templates_root() / kind
    root.mkdir(parents=True, exist_ok=True)
    return root


def templates_root() -> Path:
    root = Path(getattr(settings, "TEMPLATES_DIR", settings.DATA_DIR / "templates"))
    root.mkdir(parents=True, exist_ok=True)
    return root


def list_template_files(kind, suffix):
    directory = templates_dir(kind)
    return sorted(p.name for p in directory.glob(f"*{suffix}") if p.is_file())


def read_template_file(kind, name, suffix):
    import re
    if not re.fullmatch(r"[A-Za-z0-9._-]+", name or "") or not name.endswith(suffix):
        return None
    path = (templates_dir(kind) / name).resolve()
    if path.parent != templates_dir(kind).resolve() or not path.is_file():
        return None
    try:
        return path.read_text(encoding="utf-8", errors="replace")
    except OSError:
        return None


def write_template_file(kind, name, suffix, content):
    import re
    if not re.fullmatch(r"[A-Za-z0-9._-]+", name or ""):
        raise ValueError("invalid template name")
    if not name.endswith(suffix):
        name = f"{name}{suffix}"
    path = templates_dir(kind) / name
    path.write_text(content, encoding="utf-8")
    return path
